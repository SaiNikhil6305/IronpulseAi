"""Regenerate docs/DEPENDENCY_LICENSES.md.

Usage (from the repo root):  flutter pub deps --json > /tmp/deps.json && python3 tool/license_inventory.py /tmp/deps.json
Python licenses are read from the installed backend environment (pip install -r backend/requirements.txt).
"""
import collections
import importlib.metadata as md
import json
import re
import sys
from pathlib import Path

deps = json.load(open(sys.argv[1] if len(sys.argv) > 1 else "/tmp/deps.json"))
pkgs = {p["name"]: p for p in deps["packages"]}
root = next(p for p in deps["packages"] if p["kind"] == "root")
direct, dev = set(root["dependencies"]), set(root.get("devDependencies", []))
cache = Path.home() / ".pub-cache/hosted/pub.dev"


def detect(name: str, ver: str) -> str:
    for fn in ("LICENSE", "LICENSE.md", "LICENSE.txt", "license"):
        f = cache / f"{name}-{ver}" / fn
        if f.exists():
            t = f.read_text(errors="ignore")[:3000]
            if "Apache License" in t:
                return "Apache-2.0"
            if "Permission is hereby granted, free of charge" in t:
                return "MIT"
            if "Redistribution and use in source and binary forms" in t:
                return "BSD-3-Clause" if ("Neither the name" in t or "endorse or promote" in t) else "BSD-2-Clause"
            if "Mozilla Public License" in t:
                return "MPL-2.0"
            if "GNU" in t:
                return "GPL/LGPL — REVIEW"
            return "Other — REVIEW"
    return "SDK (BSD-3-Clause)" if pkgs[name].get("source") == "sdk" else "Not found — REVIEW"


rows = []
for n, p in sorted(pkgs.items()):
    if p["kind"] == "root":
        continue
    kind = "direct" if n in direct else ("dev" if n in dev else "transitive")
    rows.append((n, p["version"], kind, detect(n, p["version"])))
counts = collections.Counter(r[3] for r in rows)
out = ["# Dependency license inventory", "", "Generated by `tool/license_inventory.py`. Re-generate before each release. "
       "Items marked REVIEW need a manual check.", "", "## Summary (Flutter/Dart)", "", "| License | Packages |", "|---|---|"]
out += [f"| {k} | {v} |" for k, v in counts.most_common()]
out += ["", "## Flutter / Dart packages", "", "| Package | Version | Kind | License |", "|---|---|---|---|"]
out += [f"| {a} | {b} | {k} | {lic} |" for a, b, k, lic in rows]
py = []
for line in open("backend/requirements.txt"):
    name = re.split(r"[=\[<>]", line.strip())[0]
    if not name:
        continue
    try:
        m = md.metadata(name)
        lic = m.get("License-Expression") or m.get("License") or ""
        if not lic or len(lic) > 40:
            cl = [c.split("::")[-1].strip() for c in (m.get_all("Classifier") or []) if c.startswith("License ::")]
            lic = ", ".join(cl) or "REVIEW"
        py.append((name, md.version(name), lic))
    except md.PackageNotFoundError:
        py.append((name, "?", "REVIEW (not installed)"))
out += ["", "## Python backend (direct dependencies)", "", "| Package | Version | License |", "|---|---|---|"]
out += [f"| {a} | {b} | {c} |" for a, b, c in py]
Path("docs/DEPENDENCY_LICENSES.md").write_text("\n".join(out) + "\n")
print("written", counts.most_common())
